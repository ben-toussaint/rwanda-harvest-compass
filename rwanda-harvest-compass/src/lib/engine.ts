// Crop-agnostic evidence engine. Pure functions: no invented numbers —
// every output is computed from the records passed in, or is null (empty state).

export type AreaUnit = "ha" | "are" | "m2";
export const PRACTICES = ["fertilizer", "improved_seed", "pesticide", "irrigation", "agroforestry"] as const;
export type Practice = (typeof PRACTICES)[number];

export interface PlotRecord {
  crop: string;
  season: string;
  province: string;
  district: string;
  plot_area_ha: number;
  yield_t_ha: number;
  fertilizer: boolean;
  improved_seed: boolean;
  pesticide: boolean;
  irrigation: boolean;
  agroforestry: boolean;
  source: string;
  is_demo?: boolean;
  /** true when the row is a published district aggregate, not a plot observation */
  is_aggregate?: boolean;
  n_override?: number;
}

export interface MarketRecord {
  crop: string;
  province: string;
  district: string;
  selling_place: string;
  price_rwf_kg: number;
  quantity_kg?: number;
  source: string;
  is_demo?: boolean;
}

export interface SoilProfile {
  upi?: string;
  district: string;
  sector?: string;
  ph?: number;
  organic_carbon_pct?: number;
  texture?: string;
  suitability?: Record<string, string>;
  /** Verbatim RwaSIS fertilizer/lime recommendation text. Never generated by this app. */
  rwasis_recommendation?: string;
  source: "RwaSIS" | "Manual entry (RwaSIS)" | "iSDAsoil" | string;
  is_demo?: boolean;
}

export type Confidence = "High" | "Medium" | "Low";
export type Level = "district" | "province" | "national";

export function toHectares(value: number, unit: AreaUnit): number {
  if (unit === "are") return value / 100;
  if (unit === "m2") return value / 10000;
  return value;
}

export function percentile(values: number[], p: number): number | null {
  if (!values.length) return null;
  const s = [...values].sort((a, b) => a - b);
  const idx = (s.length - 1) * p;
  const lo = Math.floor(idx);
  const hi = Math.ceil(idx);
  return s[lo] + (s[hi] - s[lo]) * (idx - lo);
}

export const MIN_N = 10;

export function confidenceLabel(n: number, isAggregate = false): Confidence | null {
  if (n < MIN_N) return null;
  if (isAggregate) return "Low";
  if (n >= 100) return "High";
  if (n >= 30) return "Medium";
  return "Low";
}

export interface YieldStats {
  n: number;
  p25: number;
  median: number;
  p75: number;
  p90: number;
  max: number;
  level: Level;
  confidence: Confidence;
  isAggregate: boolean;
  sources: string[];
}

function stats(rows: PlotRecord[], level: Level): YieldStats | null {
  const isAggregate = rows.length > 0 && rows.every((r) => r.is_aggregate);
  const n = isAggregate ? rows.reduce((a, r) => a + (r.n_override ?? 1), 0) : rows.length;
  const conf = confidenceLabel(n, isAggregate);
  if (!conf || !rows.length) return null;
  const y = rows.map((r) => r.yield_t_ha);
  return {
    n,
    p25: percentile(y, 0.25)!,
    median: percentile(y, 0.5)!,
    p75: percentile(y, 0.75)!,
    p90: percentile(y, 0.9)!,
    max: Math.max(...y),
    level,
    confidence: conf,
    isAggregate,
    sources: [...new Set(rows.map((r) => r.source))],
  };
}

/** Comparable observations: same crop, widening district → province → national until n ≥ MIN_N. */
export function findCohort(
  records: PlotRecord[],
  q: { crop: string; district: string; province: string },
  filter: (r: PlotRecord) => boolean = () => true,
): { rows: PlotRecord[]; stats: YieldStats } | null {
  const crop = records.filter((r) => r.crop === q.crop && filter(r));
  const tiers: [Level, PlotRecord[]][] = [
    ["district", crop.filter((r) => r.district === q.district)],
    ["province", crop.filter((r) => r.province === q.province)],
    ["national", crop],
  ];
  for (const [level, rows] of tiers) {
    const s = stats(rows, level);
    if (s) return { rows, stats: s };
  }
  return null;
}

export type TargetClass = "within" | "above_average" | "near_ceiling" | "outside";

export function classifyTarget(target: number, s: Pick<YieldStats, "p75" | "p90" | "max">): TargetClass {
  if (target <= s.p75) return "within";
  if (target < 0.9 * s.p90) return "above_average";
  if (target <= s.max) return "near_ceiling";
  return "outside";
}

export interface FactorInsight {
  practice: Practice;
  withMedian: number;
  withoutMedian: number;
  nWith: number;
  nWithout: number;
  difference: number;
}

/** Association only: median yield of comparable plots with vs without each practice. */
export function associatedFactors(rows: PlotRecord[]): FactorInsight[] {
  if (rows.some((r) => r.is_aggregate)) return [];
  const out: FactorInsight[] = [];
  for (const p of PRACTICES) {
    const w = rows.filter((r) => r[p]).map((r) => r.yield_t_ha);
    const wo = rows.filter((r) => !r[p]).map((r) => r.yield_t_ha);
    if (w.length < MIN_N || wo.length < MIN_N) continue;
    const a = percentile(w, 0.5)!;
    const b = percentile(wo, 0.5)!;
    out.push({ practice: p, withMedian: a, withoutMedian: b, nWith: w.length, nWithout: wo.length, difference: a - b });
  }
  return out.sort((x, y) => y.difference - x.difference);
}

export interface Scenario {
  label: string;
  practices: Partial<Record<Practice, boolean>>;
  stats: YieldStats | null;
}

export function scenarios(records: PlotRecord[], q: { crop: string; district: string; province: string }): Scenario[] {
  const defs: Omit<Scenario, "stats">[] = [
    { label: "No fertilizer, local seed", practices: { fertilizer: false, improved_seed: false } },
    { label: "Fertilizer only", practices: { fertilizer: true, improved_seed: false } },
    { label: "Improved seed only", practices: { fertilizer: false, improved_seed: true } },
    { label: "Fertilizer + improved seed", practices: { fertilizer: true, improved_seed: true } },
  ];
  return defs.map((d) => {
    const c = findCohort(records, q, (r) =>
      !r.is_aggregate && Object.entries(d.practices).every(([k, v]) => r[k as Practice] === v),
    );
    return { ...d, stats: c?.stats ?? null };
  });
}

export interface PriceStats {
  level: Level;
  n: number;
  overall: { p25: number; p75: number };
  byPlace: { place: string; n: number; p25: number; p75: number }[];
  sources: string[];
}

export const MIN_PRICE_N = 5;

export function priceRange(records: MarketRecord[], q: { crop: string; district: string; province: string }): PriceStats | null {
  const crop = records.filter((r) => r.crop === q.crop);
  const tiers: [Level, MarketRecord[]][] = [
    ["district", crop.filter((r) => r.district === q.district)],
    ["province", crop.filter((r) => r.province === q.province)],
    ["national", crop],
  ];
  for (const [level, rows] of tiers) {
    if (rows.length < MIN_PRICE_N) continue;
    const prices = rows.map((r) => r.price_rwf_kg);
    const places = [...new Set(rows.map((r) => r.selling_place))];
    return {
      level,
      n: rows.length,
      overall: { p25: percentile(prices, 0.25)!, p75: percentile(prices, 0.75)! },
      byPlace: places
        .map((place) => {
          const p = rows.filter((r) => r.selling_place === place).map((r) => r.price_rwf_kg);
          return { place, n: p.length, p25: percentile(p, 0.25)!, p75: percentile(p, 0.75)! };
        })
        .filter((x) => x.n >= 3),
      sources: [...new Set(rows.map((r) => r.source))],
    };
  }
  return null;
}

/** Gross revenue range (NOT profit): estimated production (p25–p75 yield × area) × price p25–p75. */
export function grossRevenue(areaHa: number, y: { p25: number; p75: number }, price: { p25: number; p75: number }) {
  return {
    productionKg: { low: y.p25 * areaHa * 1000, high: y.p75 * areaHa * 1000 },
    revenueRwf: { low: y.p25 * areaHa * 1000 * price.p25, high: y.p75 * areaHa * 1000 * price.p75 },
  };
}

/** Soil: RwaSIS first (by UPI, then district); iSDAsoil only as fallback when enabled. */
export function findSoil(profiles: SoilProfile[], q: { upi?: string; district: string }, allowIsda = false): SoilProfile | null {
  const rw = profiles.filter((p) => p.source !== "iSDAsoil");
  const byUpi = q.upi ? rw.find((p) => p.upi === q.upi) : undefined;
  if (byUpi) return byUpi;
  const byDistrict = rw.find((p) => p.district === q.district);
  if (byDistrict) return byDistrict;
  if (allowIsda) return profiles.find((p) => p.source === "iSDAsoil" && p.district === q.district) ?? null;
  return null;
}
